"""Dump every fully rendered prompt (partials expanded, example persona/scene filled in) to one
readable markdown file, so the prompts can be reviewed the way the model will actually see them.

    python tools/render_prompts.py [output.md]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from coach import prompt_loader as pl  # noqa: E402
from coach.models import DirectorBrief, PersonaScene  # noqa: E402

MODES = ["register_shift", "pragmatic_dilemma", "think_aloud", "phrase_workout"]


def fence(text: str) -> str:
    """Wrap a prompt in a fence long enough to survive any ``` inside it."""
    ticks = "````"
    while ticks in text:
        ticks += "`"
    return f"{ticks}markdown\n{text.strip()}\n{ticks}\n"


def main(out_path: Path) -> None:
    data = json.loads((ROOT / "examples" / "persona_scene_example.json").read_text(encoding="utf-8"))
    ps = PersonaScene.model_validate(data)
    parts: list[str] = ["# Rendered prompts\n\nGenerated by `tools/render_prompts.py` from `prompts/` and `examples/`.\n"]
    titles: list[str] = []

    def section(title: str, body: str, note: str = "") -> None:
        titles.append(title)
        parts.append(f"\n---\n\n# PROMPT {title}\n")
        if note:
            parts.append(f"_{note}_\n")
        parts.append(fence(body))

    section("1. Responder: system prompt", pl.responder_system(ps.persona, ps.scene, cefr="B2"),
            "Static for the whole scene. Persona Card and Scene Bible are filled from examples/persona_scene_example.json.")
    brief = DirectorBrief(dialogue_move="SHARE", length_words=18, end_with_question=False, register="casual")
    section("2. Responder: per-turn user message", pl.responder_user(
        ps.persona.name,
        [{"speaker": "Learner", "text": "No, I can't. I have many works."}],
        brief.model_dump_json(indent=2)),
        "The director brief is produced by code (coach/director.py); the model only performs it.")
    section("3. Analyst: system prompt", pl.analyst_system(),
            "Contains the L1 Arabic transfer taxonomy, the Finding schema and the Arabic-note rules as partials.")
    section("4. Card Writer: system prompt (💡 upgrade card)", pl.card_writer_system(), "Runs lazily, only when the learner taps 💡.")
    section("5. Debrief Writer: system prompt", pl.debrief_writer_system())
    section("6. Scene Generator: system prompt", pl.scene_generator_system())

    n = 7
    for mode in MODES:
        for sec in pl.mode_sections(mode):
            kwargs = {}
            if mode == "think_aloud" and sec.upper().startswith("INTERLOCUTOR"):
                kwargs = {"persona_name": ps.persona.name, "persona_card": pl.voice_only_persona_json(ps.persona)}
            section(f"{n}. Mode `{mode}`: {sec}", pl.load_mode_prompt(mode, sec, **kwargs))
            n += 1

    toc = "\n## Contents\n\n" + "\n".join(f"- {t}" for t in titles) + "\n"
    parts.insert(1, toc)
    out_path.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out_path} ({out_path.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "RENDERED_PROMPTS.md")
